CREATE EXTENSION IF NOT EXISTS vector;
CREATE TABLE IF NOT EXISTS users (
 id text PRIMARY KEY, name text NOT NULL, email text UNIQUE NOT NULL,
 role text NOT NULL CHECK(role IN ('solicitante','operador','supervisor','administrador')),
 password_hash text NOT NULL, active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS sessions(token_hash text PRIMARY KEY,user_id text NOT NULL REFERENCES users(id),expires_at timestamptz NOT NULL);
CREATE TABLE IF NOT EXISTS tickets(
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,title text NOT NULL,description text NOT NULL,
 category text NOT NULL,priority text NOT NULL,status text NOT NULL CHECK(status IN ('aberto','em_andamento','aguardando','resolvido','encerrado')),
 version integer NOT NULL DEFAULT 1,created_by text NOT NULL REFERENCES users(id),
 created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS ticket_participants(ticket_id integer REFERENCES tickets(id),user_id text REFERENCES users(id),PRIMARY KEY(ticket_id,user_id));
CREATE TABLE IF NOT EXISTS ticket_grants(ticket_id integer REFERENCES tickets(id),user_id text REFERENCES users(id),granted_by text REFERENCES users(id),active boolean NOT NULL DEFAULT true,created_at timestamptz NOT NULL DEFAULT now(),PRIMARY KEY(ticket_id,user_id));
CREATE TABLE IF NOT EXISTS ticket_events(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ticket_id integer NOT NULL REFERENCES tickets(id),actor_id text NOT NULL REFERENCES users(id),
 kind text NOT NULL CHECK(kind IN ('criacao','comentario','evolucao')),content text NOT NULL,from_status text,to_status text,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS documents(id text PRIMARY KEY,title text NOT NULL,kind text NOT NULL,file text NOT NULL,language text,url text,license text,version integer NOT NULL,content_hash text NOT NULL);
CREATE TABLE IF NOT EXISTS chunks(
 id text PRIMARY KEY,document_id text NOT NULL,title text NOT NULL,kind text NOT NULL CHECK(kind IN ('manual','publico','ticket')),
 ticket_id integer REFERENCES tickets(id),version integer NOT NULL,content text NOT NULL,embedding vector(384) NOT NULL,
 search_vector tsvector GENERATED ALWAYS AS (to_tsvector('portuguese',content)) STORED
);
CREATE INDEX IF NOT EXISTS chunks_text_idx ON chunks USING gin(search_vector);
CREATE INDEX IF NOT EXISTS chunks_ticket_idx ON chunks(ticket_id,version);
CREATE INDEX IF NOT EXISTS grants_user_idx ON ticket_grants(user_id,ticket_id) WHERE active;
CREATE TABLE IF NOT EXISTS conversations(id uuid PRIMARY KEY,user_id text NOT NULL REFERENCES users(id),title text NOT NULL DEFAULT 'Nova conversa',created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS messages(
 id uuid PRIMARY KEY,conversation_id uuid NOT NULL REFERENCES conversations(id),user_id text NOT NULL REFERENCES users(id),role text NOT NULL CHECK(role IN ('user','assistant')),
 content text NOT NULL,result text,sources jsonb NOT NULL DEFAULT '[]',ticket_ids integer[] NOT NULL DEFAULT '{}',created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS messages_conversation_idx ON messages(conversation_id,created_at,id);
CREATE TABLE IF NOT EXISTS user_memory(user_id text PRIMARY KEY REFERENCES users(id),preferences jsonb NOT NULL DEFAULT '{"style":"curto"}',recent_ticket_ids integer[] NOT NULL DEFAULT '{}');
CREATE TABLE IF NOT EXISTS audit_log(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id text NOT NULL REFERENCES users(id),request_id text NOT NULL,action text NOT NULL,metadata jsonb NOT NULL DEFAULT '{}',created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS llm_usage(id uuid PRIMARY KEY,user_id text REFERENCES users(id),model text NOT NULL,reserved_cost numeric NOT NULL,actual_cost numeric,input_tokens integer,output_tokens integer,status text NOT NULL DEFAULT 'reserved',created_at timestamptz NOT NULL DEFAULT now());

CREATE OR REPLACE FUNCTION app_user_id() RETURNS text LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('app.user_id',true),'') $$;
CREATE OR REPLACE FUNCTION app_role() RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$ SELECT role FROM users WHERE id=app_user_id() AND active $$;
CREATE OR REPLACE FUNCTION can_read_ticket(tid integer) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
 SELECT EXISTS(SELECT 1 FROM users WHERE id=app_user_id() AND active) AND (
 EXISTS(SELECT 1 FROM ticket_participants WHERE ticket_id=tid AND user_id=app_user_id()) OR
 EXISTS(SELECT 1 FROM ticket_grants WHERE ticket_id=tid AND user_id=app_user_id() AND active))
$$;
CREATE OR REPLACE FUNCTION find_credentials(mail text) RETURNS TABLE(id text,name text,email text,role text,password_hash text) LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$ SELECT u.id,u.name,u.email,u.role,u.password_hash FROM users u WHERE u.email=lower(mail) AND active $$;
CREATE OR REPLACE FUNCTION resolve_session(token text) RETURNS TABLE(id text,name text,email text,role text) LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$ SELECT u.id,u.name,u.email,u.role FROM sessions s JOIN users u ON u.id=s.user_id WHERE s.token_hash=token AND s.expires_at>now() AND u.active $$;
CREATE OR REPLACE FUNCTION update_my_password(new_hash text) RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path=public,pg_temp AS $$ UPDATE users SET password_hash=new_hash WHERE id=app_user_id() AND active $$;
CREATE OR REPLACE FUNCTION conversation_hidden_context(cid uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
 SELECT app_role() IS NOT NULL AND EXISTS(SELECT 1 FROM messages m WHERE m.user_id=app_user_id() AND m.conversation_id=cid AND EXISTS(SELECT 1 FROM unnest(m.ticket_ids) tid WHERE NOT can_read_ticket(tid)))
$$;
CREATE OR REPLACE FUNCTION participate_on_event() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$ BEGIN INSERT INTO ticket_participants(ticket_id,user_id) VALUES(NEW.ticket_id,NEW.actor_id) ON CONFLICT DO NOTHING; RETURN NEW; END $$;
DROP TRIGGER IF EXISTS participation_event ON ticket_events;
CREATE TRIGGER participation_event AFTER INSERT ON ticket_events FOR EACH ROW EXECUTE FUNCTION participate_on_event();
CREATE OR REPLACE FUNCTION participate_on_create() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$ BEGIN INSERT INTO ticket_participants(ticket_id,user_id) VALUES(NEW.id,NEW.created_by) ON CONFLICT DO NOTHING; RETURN NEW; END $$;
DROP TRIGGER IF EXISTS participation_create ON tickets;
CREATE TRIGGER participation_create AFTER INSERT ON tickets FOR EACH ROW EXECUTE FUNCTION participate_on_create();
CREATE OR REPLACE FUNCTION reserve_generation(rid uuid,model_name text,cost numeric,budget numeric,max_calls integer) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
 DECLARE spent numeric; calls integer;
 BEGIN
  PERFORM pg_advisory_xact_lock(183323);
  SELECT coalesce(sum(coalesce(actual_cost,reserved_cost)),0),count(*) INTO spent,calls FROM llm_usage;
  IF app_role() IS NULL OR cost<0 OR budget>1 OR budget<=0 OR max_calls>100 OR spent+cost>budget OR calls>=max_calls THEN RETURN false; END IF;
  INSERT INTO llm_usage(id,user_id,model,reserved_cost) VALUES(rid,app_user_id(),model_name,cost);
  RETURN true;
 END
$$;

