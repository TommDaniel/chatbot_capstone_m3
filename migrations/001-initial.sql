DROP POLICY IF EXISTS ticket_read ON tickets;
CREATE POLICY ticket_read ON tickets FOR SELECT USING(created_by=app_user_id() OR can_read_ticket(id));
DROP POLICY IF EXISTS ticket_create ON tickets;
CREATE POLICY ticket_create ON tickets FOR INSERT WITH CHECK(created_by=app_user_id() AND app_role() IS NOT NULL);
DROP POLICY IF EXISTS ticket_update ON tickets;
CREATE POLICY ticket_update ON tickets FOR UPDATE USING(can_read_ticket(id)) WITH CHECK(can_read_ticket(id));
DROP POLICY IF EXISTS participants_read ON ticket_participants;
CREATE POLICY participants_read ON ticket_participants FOR SELECT USING(can_read_ticket(ticket_id));
DROP POLICY IF EXISTS grants_policy ON ticket_grants;
CREATE POLICY grants_policy ON ticket_grants USING(user_id=app_user_id() OR app_role()='administrador') WITH CHECK(app_role()='administrador');
DROP POLICY IF EXISTS events_read ON ticket_events;
CREATE POLICY events_read ON ticket_events FOR SELECT USING(can_read_ticket(ticket_id));
DROP POLICY IF EXISTS events_create ON ticket_events;
CREATE POLICY events_create ON ticket_events FOR INSERT WITH CHECK(actor_id=app_user_id() AND can_read_ticket(ticket_id));
DROP POLICY IF EXISTS docs_read ON documents;
CREATE POLICY docs_read ON documents FOR SELECT USING(app_role() IS NOT NULL);
DROP POLICY IF EXISTS chunks_read ON chunks;
CREATE POLICY chunks_read ON chunks FOR SELECT USING(app_role() IS NOT NULL AND (ticket_id IS NULL OR can_read_ticket(ticket_id)));
DROP POLICY IF EXISTS sessions_policy ON sessions;
CREATE POLICY sessions_policy ON sessions USING(user_id=app_user_id()) WITH CHECK(user_id=app_user_id());
DROP POLICY IF EXISTS conversations_policy ON conversations;
CREATE POLICY conversations_policy ON conversations USING(user_id=app_user_id()) WITH CHECK(user_id=app_user_id());
DROP POLICY IF EXISTS messages_read ON messages;
CREATE POLICY messages_read ON messages FOR SELECT USING(user_id=app_user_id() AND NOT EXISTS(SELECT 1 FROM unnest(ticket_ids) tid WHERE NOT can_read_ticket(tid)));
DROP POLICY IF EXISTS messages_write ON messages;
CREATE POLICY messages_write ON messages FOR INSERT WITH CHECK(user_id=app_user_id() AND app_role() IS NOT NULL AND EXISTS(SELECT 1 FROM conversations c WHERE c.id=conversation_id AND c.user_id=app_user_id()) AND NOT EXISTS(SELECT 1 FROM unnest(ticket_ids) tid WHERE NOT can_read_ticket(tid)));
DROP POLICY IF EXISTS memory_policy ON user_memory;
CREATE POLICY memory_policy ON user_memory USING(user_id=app_user_id()) WITH CHECK(user_id=app_user_id());
DROP POLICY IF EXISTS audit_policy ON audit_log;
CREATE POLICY audit_policy ON audit_log USING(user_id=app_user_id()) WITH CHECK(user_id=app_user_id());
DROP POLICY IF EXISTS usage_policy ON llm_usage;
CREATE POLICY usage_policy ON llm_usage USING(user_id=app_user_id()) WITH CHECK(user_id=app_user_id());

